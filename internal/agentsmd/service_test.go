func TestPersistenceGenerationAndBackupRestore(t *testing.T) {
	p := storage.PathsFromDataDir(t.TempDir())
	db, err := storage.Open(p)
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()
	s := agentsmd.New(db, agentsmd.Options{Now: func() string { return "123" }})
	os.MkdirAll(p.AgentsDir, 0700)
	target := filepath.Join(p.AgentsDir, "AGENTS.md")
	backup := target + ".agent-manager-backup"
	os.WriteFile(target, []byte("# Original\n"), 0600)
	snap, err := s.Create("First", "  # First\n")
	if err != nil {
		t.Fatal(err)
	}
	if snap.Fragments[0].Enabled || snap.Fragments[0].ID != 1 {
		t.Fatal(snap)
	}
	snap, err = s.SetEnabled(1, true)
	if err != nil {
		t.Fatal(err)
	}
	want := "<!-- Generated by Agent Manager. Do not edit manually. -->\n\n# First\n"
	got, _ := os.ReadFile(target)
	if string(got) != want || snap.CombinedContent != want {
		t.Fatal(string(got), snap)
	}
	got, _ = os.ReadFile(backup)
	if string(got) != "# Original\n" {
		t.Fatal(string(got))
	}
	snap, err = s.Update(1, "Edited", "# Edited")
	if err != nil {
		t.Fatal(err)
	}
	if snap.Fragments[0].ID != 1 || snap.Fragments[0].CreatedAt != "123" {
		t.Fatal(snap)
	}
	if _, err = s.SetEnabled(1, false); err != nil {
		t.Fatal(err)
	}
	got, _ = os.ReadFile(target)
	if string(got) != "# Original\n" {
		t.Fatal(string(got))
	}
	if _, err = os.Stat(backup); !os.IsNotExist(err) {
		t.Fatal("backup not consumed", err)
	}
}

func TestFailuresRestoreDatabaseTargetAndBackup(t *testing.T) {
	for _, failure := range []string{"database", "target"} {
		t.Run(failure, func(t *testing.T) {
			p := storage.PathsFromDataDir(t.TempDir())
			db, err := storage.Open(p)
			if err != nil {
				t.Fatal(err)
			}
			defer db.Close()
			os.MkdirAll(p.AgentsDir, 0700)
			target := filepath.Join(p.AgentsDir, "AGENTS.md")
			os.WriteFile(target, []byte("manual"), 0600)
			failed := false
			s := agentsmd.New(db, agentsmd.Options{WriteAtomic: func(path string, b []byte) error {
				if failure == "target" && path == target && !failed {
					failed = true
					return fmt.Errorf("injected disk failure")
				}
				return agentsmd.AtomicWrite(path, b)
			}})
			snap, err := s.Create("First", "# First")
			if err != nil {
				t.Fatal(err)
			}
			if failure == "database" {
				if _, err = db.DB.Exec("CREATE TRIGGER reject_fragment BEFORE UPDATE ON agents_md_fragments BEGIN SELECT RAISE(ABORT,'injected database failure'); END;"); err != nil {
					t.Fatal(err)
				}
			}
			if _, err = s.SetEnabled(snap.Fragments[0].ID, true); err == nil {
				t.Fatal("expected failure")
			}
			snap, err = s.Snapshot()
			if err != nil {
				t.Fatal(err)
			}
			if snap.Fragments[0].Enabled {
				t.Fatal("database changed")
			}
			got, _ := os.ReadFile(target)
			if string(got) != "manual" {
				t.Fatal(string(got))
			}
			if _, err = os.Stat(target + ".agent-manager-backup"); !os.IsNotExist(err) {
				t.Fatal("backup changed", err)
			}
		})
	}
}
func TestExistingBackupIsNeverOverwritten(t *testing.T) {
	p := storage.PathsFromDataDir(t.TempDir())
	db, err := storage.Open(p)
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()
	s := agentsmd.New(db, agentsmd.Options{})
	os.MkdirAll(p.AgentsDir, 0700)
	target := filepath.Join(p.AgentsDir, "AGENTS.md")
	os.WriteFile(target, []byte("manual"), 0600)
	os.WriteFile(target+".agent-manager-backup", []byte("old backup"), 0600)
	snap, err := s.Create("First", "# First")
	if err != nil {
		t.Fatal(err)
	}
	if _, err = s.SetEnabled(snap.Fragments[0].ID, true); err == nil {
		t.Fatal("expected backup conflict")
	}
	got, _ := os.ReadFile(target + ".agent-manager-backup")
	if string(got) != "old backup" {
		t.Fatal(string(got))
	}
}
func TestExistingDatabaseIDsOrderAndOtherDomainsSurvive(t *testing.T) {
	p := storage.PathsFromDataDir(t.TempDir())
	db, err := storage.Open(p)
	if err != nil {
		t.Fatal(err)
	}
	_, err = db.DB.Exec(`INSERT INTO agents_md_fragments VALUES(41,'Later','# Later',1,8,'old','old'),(7,'Earlier','# Earlier',0,2,'old','old'); INSERT INTO app_settings VALUES('unknown','{"keep":true}','old'); CREATE TABLE unknown_domain(id INTEGER); INSERT INTO unknown_domain VALUES(99); INSERT INTO agent_mcp_servers(id,name,transport,agents_json,enabled,created_at,updated_at) VALUES(9,'legacy','stdio','["claude"]',0,'1','1');`)
	if err != nil {
		t.Fatal(err)
	}
	db.Close()
	db, err = storage.Open(p)
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()
	s := agentsmd.New(db, agentsmd.Options{})
	snap, err := s.Snapshot()
	if err != nil {
		t.Fatal(err)
	}
	if snap.Fragments[0].ID != 7 || snap.Fragments[1].ID != 41 {
		t.Fatal(snap)
	}
	if created, err := s.Create("Newest", "# Newest"); err != nil || created.Fragments[2].ID != 42 {
		t.Fatal("new fragment must append without reordering existing entries", created, err)
	}
	if _, err = s.Delete(7); err != nil {
		t.Fatal(err)
	}
	var value string
	if err = db.DB.QueryRow("SELECT agents_json FROM agent_mcp_servers WHERE id=9").Scan(&value); err != nil || value != "[\"claude\"]" {
		t.Fatal(value, err)
	}
	if err = db.DB.QueryRow("SELECT value_json FROM app_settings WHERE key='unknown'").Scan(&value); err != nil || value != "{\"keep\":true}" {
		t.Fatal(value, err)
	}
	var id int
	if err = db.DB.QueryRow("SELECT id FROM unknown_domain").Scan(&id); err != nil || id != 99 {
		t.Fatal(id, err)
	}
	snap, err = s.Snapshot()
	if err != nil || snap.Fragments[0].ID != 41 {
		t.Fatal(snap, err)
	}
}
