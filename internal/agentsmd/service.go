// Package agentsmd manages fragment metadata and the generated global document.
package agentsmd

import (
	"database/sql"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"sync"
	"time"
	"unicode/utf8"

	"github.com/lizhian/agent-manager/internal/storage"
)

const ManagedHeader = "<!-- Generated by Agent Manager. Do not edit manually. -->"

type Fragment struct {
	ID                   int64
	Title, Content       string
	Enabled              bool
	SortOrder            int64
	CreatedAt, UpdatedAt string
}
type Snapshot struct {
	Fragments                   []Fragment
	TargetPath, CombinedContent string
	EnabledContentChars         int
}
type Options struct {
	Now         func() string
	WriteAtomic func(string, []byte) error
	OpenFolder  func(string) error
}
type Service struct {
	store      *storage.Store
	now        func() string
	write      func(string, []byte) error
	openFolder func(string) error
	mu         sync.Mutex
}

func New(store *storage.Store, options Options) *Service {
	if options.Now == nil {
		options.Now = func() string { return fmt.Sprint(time.Now().Unix()) }
	}
	if options.WriteAtomic == nil {
		options.WriteAtomic = AtomicWrite
	}
	if options.OpenFolder == nil {
		options.OpenFolder = openFolder
	}
	return &Service{store: store, now: options.Now, write: options.WriteAtomic, openFolder: options.OpenFolder}
}
func (s *Service) Snapshot() (Snapshot, error) { return s.read(s.store.DB) }

type querier interface {
	Query(string, ...any) (*sql.Rows, error)
}

func (s *Service) read(q querier) (Snapshot, error) {
	snap := Snapshot{Fragments: []Fragment{}, TargetPath: filepath.Join(s.store.Paths.AgentsDir, "AGENTS.md")}
	rows, err := q.Query("SELECT id,title,content,enabled,sort_order,created_at,updated_at FROM agents_md_fragments ORDER BY sort_order,id")
	if err != nil {
		return snap, fmt.Errorf("读取 AGENTS.md 片段失败：%w", err)
	}
	defer rows.Close()
	var bodies []string
	for rows.Next() {
		var f Fragment
		if err = rows.Scan(&f.ID, &f.Title, &f.Content, &f.Enabled, &f.SortOrder, &f.CreatedAt, &f.UpdatedAt); err != nil {
			return snap, err
		}
		snap.Fragments = append(snap.Fragments, f)
		if f.Enabled {
			bodies = append(bodies, strings.TrimSpace(f.Content))
			snap.EnabledContentChars += utf8.RuneCountInString(f.Content)
		}
	}
	if err = rows.Err(); err != nil {
		return snap, err
	}
	if len(bodies) > 0 {
		snap.CombinedContent = ManagedHeader + "\n\n" + strings.Join(bodies, "\n\n") + "\n"
	}
	return snap, nil
}
func validate(title, content string) error {
	if strings.TrimSpace(title) == "" {
		return errors.New("片段名称不能为空")
	}
	if utf8.RuneCountInString(strings.TrimSpace(title)) > 120 {
		return errors.New("片段名称不能超过 120 个字符")
	}
	if strings.TrimSpace(content) == "" {
		return errors.New("Markdown 内容不能为空")
	}
	return nil
}
func (s *Service) Create(title, content string) (Snapshot, error) {
	if err := validate(title, content); err != nil {
		return Snapshot{}, err
	}
	return s.mutate("新增片段 "+strings.TrimSpace(title), func(tx *sql.Tx) error {
		now := s.now()
		_, err := tx.Exec("INSERT INTO agents_md_fragments(id,title,content,enabled,sort_order,created_at,updated_at) SELECT coalesce(max(id),0)+1,?,?,0,coalesce(max(sort_order),-1)+1,?,? FROM agents_md_fragments", strings.TrimSpace(title), content, now, now)
		return err
	})
}
func (s *Service) Update(id int64, title, content string) (Snapshot, error) {
	if err := validate(title, content); err != nil {
		return Snapshot{}, err
	}
	return s.mutate(fmt.Sprintf("更新片段 %d", id), func(tx *sql.Tx) error {
		return changed(tx.Exec("UPDATE agents_md_fragments SET title=?,content=?,updated_at=? WHERE id=?", strings.TrimSpace(title), content, s.now(), id))
	})
}
func (s *Service) SetEnabled(id int64, enabled bool) (Snapshot, error) {
	return s.mutate(fmt.Sprintf("切换片段 %d", id), func(tx *sql.Tx) error {
		return changed(tx.Exec("UPDATE agents_md_fragments SET enabled=?,updated_at=? WHERE id=?", enabled, s.now(), id))
	})
}
func (s *Service) Delete(id int64) (Snapshot, error) {
	return s.mutate(fmt.Sprintf("删除片段 %d", id), func(tx *sql.Tx) error {
		if err := changed(tx.Exec("DELETE FROM agents_md_fragments WHERE id=?", id)); err != nil {
			return err
		}
		snap, err := s.read(tx)
		if err != nil {
			return err
		}
		for i, f := range snap.Fragments {
			if _, err = tx.Exec("UPDATE agents_md_fragments SET sort_order=? WHERE id=?", i, f.ID); err != nil {
				return err
			}
		}
		return nil
	})
}
func changed(result sql.Result, err error) error {
	if err != nil {
		return err
	}
	n, err := result.RowsAffected()
	if err != nil {
		return err
	}
	if n == 0 {
		return errors.New("AGENTS.md 片段不存在，请刷新后重试")
	}
	return nil
}
func (s *Service) mutate(action string, change func(*sql.Tx) error) (Snapshot, error) {
	s.mu.Lock()
	defer s.mu.Unlock()
	fail := func(err error) (Snapshot, error) { return Snapshot{}, fmt.Errorf("%s 失败：%w", action, err) }
	tx, err := s.store.DB.Begin()
	if err != nil {
		return fail(err)
	}
	defer tx.Rollback()
	if err = change(tx); err != nil {
		return fail(err)
	}
	snap, err := s.read(tx)
	if err != nil {
		return fail(err)
	}
	backup := snap.TargetPath + ".agent-manager-backup"
	oldTarget, err := capture(snap.TargetPath)
	if err != nil {
		return fail(err)
	}
	oldBackup, err := capture(backup)
	if err != nil {
		return fail(err)
	}
	restore := func(cause error) (Snapshot, error) {
		return fail(errors.Join(cause, s.restore(snap.TargetPath, oldTarget), s.restore(backup, oldBackup)))
	}
	if err = s.sync(snap, oldTarget, oldBackup); err != nil {
		return restore(err)
	}
	if err = tx.Commit(); err != nil {
		return restore(fmt.Errorf("提交数据库失败：%w", err))
	}
	// The snapshot was read from the persisted rows in this transaction, after the write.
	return snap, nil
}

type fileState struct {
	exists  bool
	content []byte
}

func capture(path string) (fileState, error) {
	info, err := os.Lstat(path)
	if os.IsNotExist(err) {
		return fileState{}, nil
	}
	if err != nil {
		return fileState{}, err
	}
	if !info.Mode().IsRegular() {
		return fileState{}, fmt.Errorf("%s 不是普通文件，无法安全接管", path)
	}
	bytes, err := os.ReadFile(path)
	return fileState{exists: true, content: bytes}, err
}
func (s *Service) restore(path string, state fileState) error {
	current, err := capture(path)
	if err != nil {
		return fmt.Errorf("恢复 %s 失败：%w", path, err)
	}
	if current.exists == state.exists && string(current.content) == string(state.content) {
		return nil
	}
	if state.exists {
		err = s.write(path, state.content)
	} else {
		err = os.Remove(path)
		if os.IsNotExist(err) {
			err = nil
		}
	}
	if err != nil {
		return fmt.Errorf("恢复 %s 失败：%w", path, err)
	}
	return nil
}
func (s *Service) sync(snap Snapshot, target, backup fileState) error {
	backupPath := snap.TargetPath + ".agent-manager-backup"
	managed := target.exists && strings.HasPrefix(string(target.content), ManagedHeader)
	if snap.CombinedContent == "" {
		if managed {
			if err := os.Remove(snap.TargetPath); err != nil {
				return err
			}
			target.exists = false
		}
		if !target.exists && backup.exists {
			return os.Rename(backupPath, snap.TargetPath)
		}
		return nil
	}
	if target.exists && !managed {
		if backup.exists {
			return fmt.Errorf("检测到未受管的 %s，且备份文件已存在；请先处理这两个文件", snap.TargetPath)
		}
		if err := s.write(backupPath, target.content); err != nil {
			return err
		}
	}
	return s.write(snap.TargetPath, []byte(snap.CombinedContent))
}

// AtomicWrite keeps the old file intact until replacement succeeds.
func AtomicWrite(path string, data []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0700); err != nil {
		return err
	}
	mode := os.FileMode(0600)
	if info, err := os.Stat(path); err == nil {
		mode = info.Mode().Perm()
	}
	f, err := os.CreateTemp(filepath.Dir(path), ".agent-manager-*.tmp")
	if err != nil {
		return err
	}
	defer os.Remove(f.Name())
	if err = f.Chmod(mode); err == nil {
		_, err = f.Write(data)
	}
	if err == nil {
		err = f.Sync()
	}
	closeErr := f.Close()
	if err == nil {
		err = closeErr
	}
	if err != nil {
		return err
	}
	return os.Rename(f.Name(), path)
}
